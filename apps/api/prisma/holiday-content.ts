import { PriceType } from '@prisma/client';

type Item = {
  title: string;
  descriptionHtml: string;
  priceType: PriceType;
  amount: number | null;
  priceUnit: string | null;
  priceNote: string | null;
  durationMinutes: number | null;
  ageLabel: string | null;
};

type Category = {
  slug: string;
  title: string;
  description: string;
  items: Item[];
};

// Цены взяты из присланного прайса. В БД денежные суммы хранятся в копейках.
function item(
  title: string,
  rubles: number | null,
  description: string,
  options: Partial<Omit<Item, 'title' | 'amount' | 'descriptionHtml'>> = {},
): Item {
  return {
    title,
    amount: rubles === null ? null : rubles * 100,
    descriptionHtml: `<p>${description}</p>`,
    priceType: rubles === null ? PriceType.ON_REQUEST : PriceType.FIXED,
    priceUnit: null,
    priceNote: null,
    durationMinutes: null,
    ageLabel: null,
    ...options,
  };
}

function program(title: string, rubles: number, age: string | null, description: string): Item {
  return item(title, rubles, description, { ageLabel: age, durationMinutes: 60 });
}

